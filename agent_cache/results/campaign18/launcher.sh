#!/usr/bin/env bash
# Campaigns 18 (x70) and 19 (x10) on the redesigned client (REPLAY_REDESIGN.md section 9.2), one after the other: the
# original HiCache baseline and oracle v2 + next-use, 768 users at 0.1/s, all recorded turns, C=128, 5 h per arm, hints
# sent in both arms, the frozen v2 engine.
#   host: docker exec -d sglang_hicache bash -c 'nohup bash /sgl-workspace/sglang/agent_cache/frozen/oracle_scripts_staging/c18_c19.sh >> /sgl-workspace/sglang/agent_cache/results/campaign18/launcher.log 2>&1'
# Resumable: each campaign dir keeps a manifest (arm, run dir, client dir); a relaunch runs only the arms missing from it,
# in a new compare dir. Stops (STOP line) when an arm is missing after its campaign, so campaign 19 never starts after a
# failed campaign 18 arm. Do not edit this file or agent_cache/scripts/ while it runs.
# Stop: pkill -f "[c]18_c19.sh"; pkill -f "^bash [r]un_compare.sh"; pkill -f "[r]eplay_agentic.py"; bash stop_server.sh
set -uo pipefail
AC=/sgl-workspace/sglang/agent_cache
cd "$AC/scripts" || { echo "STOP: $AC/scripts missing (run inside the container)"; exit 1; }
ENGINE=$(ls -d "$AC/frozen/engine_5df71c4bf0_v2/python") || { echo "STOP: frozen engine missing"; exit 1; }
ALL_ARMS="three_tier_wc three_tier_wc_oracle_v2_nu"

missing() { local A M=""; for A in $ALL_ARMS; do grep -q "^$A " "$1/manifest.txt" || M="$M $A"; done; echo "${M# }"; }

run_one() {   # <campaign dir> <gap scale>
  local CD=$1 G=$2 TODO LOG IOS rc CMP M
  mkdir -p "$CD"; touch "$CD/manifest.txt"
  TODO=$(missing "$CD")
  [ -z "$TODO" ] && { echo "$(date -u +%FT%TZ) $(basename "$CD"): nothing left"; return 0; }
  LOG="$CD/driver_$(date -u +%m%d_%H%M%S).log"
  nohup iostat -dxt vdc 10 >> "$CD/iostat_vdc.log" 2>&1 < /dev/null & IOS=$!
  echo "LAUNCH $(date -u +%FT%TZ) $(basename "$CD") arms: $TODO gaps x$G commit $(git -c safe.directory='*' -C "$AC" rev-parse --short HEAD) engine $ENGINE -> $LOG"
  ARMS="$TODO" LEVEL=NAT160 MODEL=Qwen/Qwen3-30B-A3B-Instruct-2507 CTX=131072 KV_DTYPE=auto TEMPLATE= L3_CLEANER_PCT=70,60 \
    TRACE="$AC/traces/lmcache_agentic_trace_262k.json" USERS=768 TURNS=50 ARRIVAL=0.1 GAP="$G" C=128 SEED=0 \
    ORACLE_HINTS=1 CLIENT_TIMEOUT=18000 SGLANG_TIMEOUT_KEEP_ALIVE=3600 ENGINE_PYTHONPATH="$ENGINE" \
    bash run_compare.sh > "$LOG" 2>&1
  rc=$?
  kill "$IOS" 2>/dev/null
  CMP=$(grep -a '^compare dir: ' "$LOG" | cut -d' ' -f3)
  if [ -n "$CMP" ] && [ -f "$CMP/manifest.txt" ]; then
    cat "$CMP/manifest.txt" >> "$CD/manifest.txt"; cp "$CMP/config.txt" "$CD/config_$(basename "$CMP").txt"
  fi
  echo "$(date -u +%FT%TZ) $(basename "$CD"): run_compare rc=$rc, $(grep -ac '^STAGE DONE' "$LOG") done, $(grep -ac '^STAGE FAILED' "$LOG") failed, compare dir ${CMP:-none}"
  M=$(missing "$CD")
  [ -z "$M" ] || { echo "STOP: $(basename "$CD") is missing: $M (read $LOG; relaunch to retry only those arms)"; return 1; }
}

run_one "$AC/results/campaign18" 70 && run_one "$AC/results/campaign19" 10 && echo "CAMPAIGNS DONE $(date -u +%FT%TZ)"
