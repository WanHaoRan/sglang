#!/usr/bin/env bash
# Campaign 21: x10 gaps with 44 users in session and 70 GB of host memory, where a forecast should have to work (results/campaign20/DECISIONS.md,
# "Lower cap, smaller memory or more load?"). Three arms on the frozen v2 engine, oracle first so that a bad setting shows before the other two run.
#   host: docker exec -d sglang_hicache bash -c 'nohup bash /sgl-workspace/sglang/agent_cache/frozen/oracle_scripts_staging/c21_x10_c44/c21.sh >> /sgl-workspace/sglang/agent_cache/results/campaign21/launcher.log 2>&1'
# Resumable: results/campaign21/manifest.txt keeps a line per finished arm; a relaunch runs only the missing ones. Stops at the first arm with no result.
# Do not edit this file or agent_cache/scripts/ while it runs.
# Stop: pkill -f "[c]21.sh"; pkill -f "^bash [r]un_compare.sh"; pkill -f "[r]eplay_agentic.py"; bash stop_server.sh
set -uo pipefail
AC=/sgl-workspace/sglang/agent_cache
CD=$AC/results/campaign21
cd "$AC/scripts" || { echo "STOP: $AC/scripts missing (run inside the container)"; exit 1; }
ENGINE=$(ls -d "$AC/frozen/engine_5df71c4bf0_v2/python") || { echo "STOP: frozen engine missing"; exit 1; }
mkdir -p "$CD"; touch "$CD/manifest.txt"
[ -f "$CD/scripts_at_launch.tgz" ] || tar czf "$CD/scripts_at_launch.tgz" --exclude='__pycache__' -C "$AC" scripts

run_arm() {   # <manifest label> <server arm> <ORACLE_HINTS> <HINTS>
  local L=$1 A=$2 OH=$3 H=$4 LOG IOS rc CMP
  grep -q "^$L " "$CD/manifest.txt" && { echo "C21 $L already done"; return 0; }
  LOG="$CD/driver_${L}_$(date -u +%m%d_%H%M%S).log"
  nohup iostat -dxt vdc 10 >> "$CD/iostat_vdc.log" 2>&1 < /dev/null & IOS=$!
  echo "C21 $L LAUNCH $(date -u +%FT%TZ) commit $(git -c safe.directory='*' -C "$AC" rev-parse --short HEAD) engine $ENGINE -> $LOG"
  ARMS="$A" LEVEL=NAT160 HOST_GB=70 MODEL=Qwen/Qwen3-30B-A3B-Instruct-2507 CTX=131072 KV_DTYPE=auto TEMPLATE= L3_CLEANER_PCT=70,60 \
    TRACE="$AC/traces/lmcache_agentic_trace_262k.json" USERS=768 TURNS=50 ARRIVAL=0.1 GAP=10 C=44 SEED=0 \
    ORACLE_HINTS="$OH" HINTS="$H" CLIENT_TIMEOUT=7200 SGLANG_TIMEOUT_KEEP_ALIVE=3600 ENGINE_PYTHONPATH="$ENGINE" \
    bash run_compare.sh > "$LOG" 2>&1
  rc=$?
  kill "$IOS" 2>/dev/null
  CMP=$(grep -a '^compare dir: ' "$LOG" | cut -d' ' -f3)
  if [ -n "$CMP" ] && [ -s "$CMP/manifest.txt" ]; then
    awk -v L="$L" 'NR == 1 { print L, $2, $3 }' "$CMP/manifest.txt" >> "$CD/manifest.txt"
    cp "$CMP/config.txt" "$CD/config_$L.txt"
    echo "C21 $L DONE $(date -u +%FT%TZ) run_compare rc=$rc, compare dir $CMP"
  else
    echo "C21 $L STOP $(date -u +%FT%TZ) run_compare rc=$rc, no manifest: read $LOG"
    return 1
  fi
}

run_arm three_tier_wc_oracle_v2_nu three_tier_wc_oracle_v2_nu 1 oracle \
  && run_arm three_tier_wc_oracle_v2_nu_p50 three_tier_wc_oracle_v2_nu 0 dist \
  && run_arm three_tier_wc three_tier_wc 1 oracle \
  && echo "C21 ALL DONE $(date -u +%FT%TZ)"
