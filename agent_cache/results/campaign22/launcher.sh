#!/usr/bin/env bash
# Campaign 22: where does the x10 gain come from? Campaign 19's workload, adding one change at a time (results/campaign22/DECISIONS.md). Waits for campaign 21 to end,
# then installs the new arms into scripts/start_server.sh, unless that file changed since this was prepared. It first runs campaign 21's hint-free arm (campaign 21's setting, in its manifest),
# then campaign 22's three arms. Campaign 19 holds both ends of the ladder.
#   host: docker exec -d sglang_hicache bash -c 'nohup bash /sgl-workspace/sglang/agent_cache/frozen/oracle_scripts_staging/c22_ladder/c22.sh >> /sgl-workspace/sglang/agent_cache/results/campaign22/launcher.log 2>&1'
# While waiting: touch results/campaign22/GO to start without campaign 21's end line, or results/campaign22/CANCEL to give up.
# Resumable: results/campaign22/manifest.txt keeps a line per finished arm. Stops at the first arm with no result. Do not edit this file or agent_cache/scripts/ while it runs.
# Stop: pkill -f "[c]22.sh"; pkill -f "^bash [r]un_compare.sh"; pkill -f "[r]eplay_agentic.py"; bash stop_server.sh
set -uo pipefail
AC=/sgl-workspace/sglang/agent_cache
CD=$AC/results/campaign22
STAGED=$AC/frozen/oracle_scripts_staging/c22_ladder/start_server.sh
SCRIPT=$AC/scripts/start_server.sh
ORIGINAL_SHA=d60cad9c9e228c6ad8c4453217eb69dc7c2d9853abc96935167214486a7c80a8
C21_LOG=$AC/results/campaign21/launcher.log
ENGINE=$(ls -d "$AC/frozen/engine_5df71c4bf0_v2/python") || { echo "C22 STOP: frozen engine missing"; exit 1; }
mkdir -p "$CD"; touch "$CD/manifest.txt"

echo "C22 WAITING $(date -u +%FT%TZ) for campaign 21"
while :; do
  [ -f "$CD/CANCEL" ] && { echo "C22 CANCELLED $(date -u +%FT%TZ)"; exit 0; }
  [ -f "$CD/GO" ] && { echo "C22 GO file $(date -u +%FT%TZ)"; break; }
  grep -q '^C21 ALL DONE' "$C21_LOG" && { echo "C22 campaign 21 done $(date -u +%FT%TZ)"; break; }
  if grep -q '^C21 .* STOP ' "$C21_LOG"; then
    echo "C22 NOT STARTED $(date -u +%FT%TZ): campaign 21 stopped on a failed arm; read $C21_LOG, then touch $CD/GO and relaunch"
    exit 1
  fi
  sleep 60
done
for i in $(seq 1 60); do pgrep -f '^bash run_compare.sh' > /dev/null || break; sleep 10; done
if pgrep -f '^bash run_compare.sh' > /dev/null; then echo "C22 STOP $(date -u +%FT%TZ): run_compare.sh is still running"; exit 1; fi

cd "$AC/scripts" || { echo "C22 STOP: $AC/scripts missing"; exit 1; }
CUR=$(sha256sum "$SCRIPT" | cut -d' ' -f1); NEW=$(sha256sum "$STAGED" | cut -d' ' -f1)
if [ "$CUR" = "$ORIGINAL_SHA" ]; then
  cat "$STAGED" > "$SCRIPT"; echo "C22 installed the new arms in scripts/start_server.sh"
elif [ "$CUR" != "$NEW" ]; then
  echo "C22 STOP $(date -u +%FT%TZ): scripts/start_server.sh changed since this was prepared (sha $CUR); add the arms from $STAGED by hand and relaunch"
  exit 1
fi
[ -f "$CD/scripts_at_launch.tgz" ] || tar czf "$CD/scripts_at_launch.tgz" --exclude='__pycache__' -C "$AC" scripts

run_arm() {   # <server arm> <campaign dir> <users in session> <host GB, empty for the level's>
  local A=$1 D=$2 N=$3 G=$4 LOG IOS rc CMP
  grep -q "^$A " "$D/manifest.txt" && { echo "C22 $A already done"; return 0; }
  LOG="$D/driver_${A}_$(date -u +%m%d_%H%M%S).log"
  nohup iostat -dxt vdc 10 >> "$D/iostat_vdc.log" 2>&1 < /dev/null & IOS=$!
  echo "C22 $A LAUNCH $(date -u +%FT%TZ) commit $(git -c safe.directory='*' -C "$AC" rev-parse --short HEAD) engine $ENGINE -> $LOG"
  ARMS="$A" LEVEL=NAT160 HOST_GB="$G" MODEL=Qwen/Qwen3-30B-A3B-Instruct-2507 CTX=131072 KV_DTYPE=auto TEMPLATE= L3_CLEANER_PCT=70,60 \
    TRACE="$AC/traces/lmcache_agentic_trace_262k.json" USERS=768 TURNS=50 ARRIVAL=0.1 GAP=10 C="$N" SEED=0 \
    ORACLE_HINTS=1 CLIENT_TIMEOUT=7200 SGLANG_TIMEOUT_KEEP_ALIVE=3600 ENGINE_PYTHONPATH="$ENGINE" \
    bash run_compare.sh > "$LOG" 2>&1
  rc=$?
  kill "$IOS" 2>/dev/null
  CMP=$(grep -a '^compare dir: ' "$LOG" | cut -d' ' -f3)
  if [ -n "$CMP" ] && [ -s "$CMP/manifest.txt" ]; then
    cat "$CMP/manifest.txt" >> "$D/manifest.txt"; cp "$CMP/config.txt" "$D/config_$A.txt"
    echo "C22 $A DONE $(date -u +%FT%TZ) run_compare rc=$rc, compare dir $CMP"
  else
    echo "C22 $A STOP $(date -u +%FT%TZ) run_compare rc=$rc, no manifest: read $LOG"
    return 1
  fi
}

C21=$AC/results/campaign21
run_arm three_tier_wc_dl_poll0 "$C21" 44 70 \
  && run_arm three_tier_wc_poll0 "$CD" 128 "" \
  && run_arm three_tier_wc_dl_poll0 "$CD" 128 "" \
  && run_arm three_tier_wc_oracle_v2 "$CD" 128 "" \
  && echo "C22 ALL DONE $(date -u +%FT%TZ)"
